// Writes scripts/blender/layout.json from src/scene/layout.ts, so the Blender scene uses exactly the
// positions, sizes and lights of the live room. Run it before every Blender build (npm run models:layout).
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const vite = await createServer({ root, configFile: false, logLevel: 'error', server: { middlewareMode: true }, appType: 'custom' });
try {
  const L = await vite.ssrLoadModule('/src/scene/layout.ts');
  const v = (p) => [p.x, p.y, p.z];
  const layout = {
    _note: 'Generated by scripts/blender/layout.mjs from src/scene/layout.ts. three.js space: metres, y up.',
    ROOM: L.ROOM, WIN: L.WIN, DESK: L.DESK, TOP: L.TOP, CW: L.CW, BOARD: L.BOARD, BOARD_AT: L.BOARD_AT,
    DIPLOMA: L.DIPLOMA, CABINET: L.CABINET, EVIDENCE_BOX: L.EVIDENCE_BOX, COAT_RACK: L.COAT_RACK,
    LIGHTS: L.LIGHTS,
    HOME: { pos: v(L.HOME.pos), target: v(L.HOME.target) },
  };
  const out = join(root, 'scripts/blender/layout.json');
  writeFileSync(out, JSON.stringify(layout, null, 2) + '\n');
  console.log(`layout: wrote ${out}`);
} finally {
  await vite.close();
}
